"""Experiment table: one row per run directory, built from validation results only.

The table and the seed-noise summary are written between two markers of a Markdown file
(``docs/EXPERIMENTS.md``); everything outside the markers is hand-written and left untouched.
Runs that failed or did not finish stay in the table, flagged in the notes column.
"""

from __future__ import annotations

import re
import statistics
from fnmatch import fnmatch
from pathlib import Path

from vic.config import load_yaml
from vic.metrics import caption_statistics
from vic.utils import read_json

BEGIN_MARKER = "<!-- experiments:begin (generated by scripts/update_experiments.py) -->"
END_MARKER = "<!-- experiments:end -->"
DEFAULT_EXCLUDE = ("smoke*", "debug*", "tmp*")
SEED_SUFFIX = re.compile(r"_seed\d+$")
STATUS_NOTES = {"interrupted": "chưa chạy xong", "failed": "lỗi", "missing": "chưa có kết quả"}

DOCUMENT_TEMPLATE = f"""# Bảng thí nghiệm

Mỗi dòng là một lần huấn luyện trong `outputs/`. **Mọi số liệu đều đo trên tập val**; tập test
không xuất hiện ở đây. Phần giữa hai dấu mốc bên dưới do `scripts/update_experiments.py` (và
`scripts/run_sweep.py`) sinh ra, không sửa tay; ghi chú và phân tích viết ở các mục sau nó.

{BEGIN_MARKER}
{END_MARKER}
"""


def run_status(summary: dict | None, config: dict) -> str:
    """ "completed", "interrupted", "failed", or "missing" when there is no summary yet."""
    if summary is None:
        return "missing"
    if "status" in summary:
        return summary["status"]
    # Summaries written before the status field existed.
    finished = summary.get("epochs_completed") == config.get("train", {}).get("epochs")
    return "completed" if finished else "interrupted"


def _parameter_count(summary: dict, run_dir: Path) -> int | None:
    if summary.get("parameter_count") is not None:
        return int(summary["parameter_count"])
    checkpoint = run_dir / "checkpoints" / "best.pt"
    if not checkpoint.exists():
        return None
    from vic.engine.checkpoint import load_checkpoint  # imports torch; only for old summaries

    return sum(tensor.numel() for tensor in load_checkpoint(checkpoint)["decoder"].values())


def _train_minutes(summary: dict) -> tuple[float | None, bool]:
    """Total training time in minutes and whether it is an estimate (old summaries)."""
    if summary.get("train_seconds") is not None:
        return summary["train_seconds"] / 60, False
    per_epoch, epochs = summary.get("estimated_epoch_minutes"), summary.get("epochs_completed")
    if per_epoch is None or not epochs:
        return None, False
    return per_epoch * epochs, True


def _evaluation(run_dir: Path, beam_size: int) -> dict | None:
    path = run_dir / f"eval_val_beam{beam_size}.json"
    return read_json(path) if path.exists() else None


def collect_run(run_dir: Path, beam_size: int = 3) -> dict:
    """Everything the table shows about one run; missing pieces are None."""
    config = load_yaml(run_dir / "config.yaml")
    summary_path = run_dir / "summary.json"
    summary = read_json(summary_path) if summary_path.exists() else None
    status = run_status(summary, config)
    summary = summary or {}
    encoder = config.get("model", {}).get("encoder", {})
    row = {
        "run": run_dir.name,
        "group": SEED_SUFFIX.sub("", run_dir.name),
        "encoder": f"{encoder.get('name', '?')} @{encoder.get('image_size', '?')}",
        "decoder": config.get("model", {}).get("decoder", {}).get("type", "?"),
        "seed": config.get("seed"),
        "status": status,
        "error": summary.get("error"),
        "notes": str(config.get("notes") or ""),
        "commit": summary.get("git_commit"),
        "peak_vram_mb": summary.get("peak_vram_allocated_mb"),
        "best_epoch": summary.get("best_epoch"),
        "parameters": _parameter_count(summary, run_dir),
        "cider": None,
        "bleu4": None,
        "cider_greedy": None,
        "diagnostics": None,
        "reference_diagnostics": None,
    }
    row["train_minutes"], row["train_minutes_estimated"] = _train_minutes(summary)

    evaluation = _evaluation(run_dir, beam_size)
    if evaluation is not None:
        row["cider"] = evaluation["scores"]["CIDEr"]
        row["bleu4"] = evaluation["scores"]["BLEU-4"]
        row["best_epoch"] = evaluation.get("training_progress", {}).get("epoch", row["best_epoch"])
        row["diagnostics"] = evaluation.get("diagnostics") or caption_statistics(
            caption.split() for caption in evaluation["predictions"].values()
        )
        row["reference_diagnostics"] = evaluation.get("reference_diagnostics")
    greedy = _evaluation(run_dir, 1)
    if greedy is not None:
        row["cider_greedy"] = greedy["scores"]["CIDEr"]
    return row


def collect_runs(
    outputs_dir: str | Path, beam_size: int = 3, exclude: tuple[str, ...] = DEFAULT_EXCLUDE
) -> list[dict]:
    """Rows for every run directory under ``outputs_dir``, oldest first."""
    outputs_dir = Path(outputs_dir)
    if not outputs_dir.is_dir():
        return []
    run_dirs = [
        path
        for path in outputs_dir.iterdir()
        if (path / "config.yaml").exists()
        and not any(fnmatch(path.name, pattern) for pattern in exclude)
    ]
    run_dirs.sort(key=lambda path: ((path / "config.yaml").stat().st_mtime, path.name))
    return [collect_run(path, beam_size) for path in run_dirs]


def _cell(value, pattern: str = "{}") -> str:
    return "—" if value is None else pattern.format(value)


def experiments_table(rows: list[dict], beam_size: int = 3) -> list[str]:
    header = [
        "Run", "Encoder", "Decoder", "Seed", f"CIDEr (beam {beam_size})", "BLEU-4",
        "CIDEr (greedy)", "Câu khác nhau", "Âm tiết khác nhau", "Độ dài TB", "Lặp 2-gram (%)",
        "Lặp 3-gram (%)", "Tham số (triệu)", "Huấn luyện (phút)", "VRAM đỉnh (MB)",
        "Epoch tốt nhất", "Commit", "Ghi chú",
    ]  # fmt: skip
    lines = ["| " + " | ".join(header) + " |", "|---|---|---|---:" + "|---:" * 12 + "|---|---|"]
    for row in rows:
        stats = row["diagnostics"] or {}
        minutes = _cell(row["train_minutes"], "{:.1f}")
        if row["train_minutes_estimated"]:
            minutes = f"~{minutes}"
        notes = [row["notes"]] if row["notes"] else []
        if row["status"] != "completed":
            note = STATUS_NOTES.get(row["status"], row["status"])
            notes.append(f"**{note}**" + (f": {row['error']}" if row["error"] else ""))
        cells = [
            f"`{row['run']}`",
            row["encoder"],
            row["decoder"],
            _cell(row["seed"]),
            _cell(row["cider"], "{:.4f}"),
            _cell(None if row["bleu4"] is None else row["bleu4"] * 100, "{:.2f}"),
            _cell(row["cider_greedy"], "{:.4f}"),
            _cell(stats.get("distinct_captions")),
            _cell(stats.get("distinct_tokens")),
            _cell(stats.get("mean_length"), "{:.1f}"),
            _cell(_percent(stats.get("repeated_bigram_rate")), "{:.1f}"),
            _cell(_percent(stats.get("repeated_trigram_rate")), "{:.1f}"),
            _cell(None if row["parameters"] is None else row["parameters"] / 1e6, "{:.2f}"),
            minutes,
            _cell(row["peak_vram_mb"], "{:.0f}"),
            _cell(row["best_epoch"]),
            _cell(row["commit"], "`{}`"),
            "; ".join(notes).replace("|", "/").replace("\n", " "),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def _percent(rate: float | None) -> float | None:
    return None if rate is None else 100 * rate


def reference_line(rows: list[dict]) -> list[str]:
    """Statistics of the human reference captions, for comparison with the table."""
    for row in rows:
        stats = row["reference_diagnostics"]
        if stats:
            return [
                "",
                f"Để so sánh, {stats['num_captions']} câu tham chiếu của tập val: "
                f"{stats['distinct_tokens']} âm tiết khác nhau, độ dài trung bình "
                f"{stats['mean_length']:.1f}, lặp 2-gram "
                f"{100 * stats['repeated_bigram_rate']:.1f}%, lặp 3-gram "
                f"{100 * stats['repeated_trigram_rate']:.1f}%.",
            ]
    return []


def seed_noise(rows: list[dict]) -> list[dict]:
    """Mean and sample standard deviation over seeds, for groups with at least two runs.

    Runs named ``<name>_seed<N>`` belong to the group ``<name>``.
    """
    groups: dict[str, list[dict]] = {}
    for row in rows:
        if row["status"] == "completed" and row["cider"] is not None:
            groups.setdefault(row["group"], []).append(row)
    result = []
    for name, members in groups.items():
        if len(members) < 2:
            continue
        ciders = [member["cider"] for member in members]
        bleus = [member["bleu4"] * 100 for member in members]
        result.append(
            {
                "group": name,
                "seeds": sorted(member["seed"] for member in members),
                "cider_mean": statistics.fmean(ciders),
                "cider_std": statistics.stdev(ciders),
                "bleu4_mean": statistics.fmean(bleus),
                "bleu4_std": statistics.stdev(bleus),
            }
        )
    return result


def seed_noise_table(rows: list[dict], beam_size: int = 3) -> list[str]:
    noise = seed_noise(rows)
    if not noise:
        return []
    lines = [
        "",
        "### Độ nhiễu giữa các seed",
        "",
        "Trung bình ± độ lệch chuẩn mẫu của các run cùng cấu hình, chỉ khác seed "
        f"(beam {beam_size}).",
        "",
        "| Cấu hình | Seed | CIDEr | BLEU-4 |",
        "|---|---|---:|---:|",
    ]
    for item in noise:
        seeds = ", ".join(str(seed) for seed in item["seeds"])
        lines.append(
            f"| `{item['group']}` | {seeds} | {item['cider_mean']:.4f} ± {item['cider_std']:.4f} | "
            f"{item['bleu4_mean']:.2f} ± {item['bleu4_std']:.2f} |"
        )
    return lines


def render_experiments(rows: list[dict], beam_size: int = 3) -> str:
    lines = experiments_table(rows, beam_size) + reference_line(rows)
    lines += seed_noise_table(rows, beam_size)
    return "\n".join(lines)


def update_experiments_doc(
    outputs_dir: str | Path = "outputs",
    doc_path: str | Path = "docs/EXPERIMENTS.md",
    beam_size: int = 3,
    exclude: tuple[str, ...] = DEFAULT_EXCLUDE,
) -> list[dict]:
    """Regenerate the table inside ``doc_path`` (created from a template when missing)."""
    doc_path = Path(doc_path)
    rows = collect_runs(outputs_dir, beam_size, exclude)
    text = doc_path.read_text(encoding="utf-8") if doc_path.exists() else DOCUMENT_TEMPLATE
    if BEGIN_MARKER not in text or END_MARKER not in text:
        raise ValueError(f"{doc_path} lacks the experiment table markers")
    before, _, rest = text.partition(BEGIN_MARKER)
    _, _, after = rest.partition(END_MARKER)
    generated = f"{BEGIN_MARKER}\n\n{render_experiments(rows, beam_size)}\n\n{END_MARKER}"
    doc_path.parent.mkdir(parents=True, exist_ok=True)
    doc_path.write_text(before + generated + after, encoding="utf-8", newline="\n")
    return rows
